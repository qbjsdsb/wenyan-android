package com.wenyan.app.core.designsystem.component

import androidx.compose.ui.unit.dp

/**
 * 间距 tokens（6 级），统一全 App 间距体系。
 *
 * - [xs]：4dp — 图标与文字间距
 * - [sm]：8dp — 卡片内元素间距
 * - [md]：12dp — 卡片间距、列表项间距
 * - [lg]：16dp — 屏幕边距、卡片内 padding
 * - [xl]：24dp — 区块间距
 * - [xxl]：32dp — 页面级间距
 */
object Spacing {
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp
}
