def classify_question(q):
    """根据题目内容和答案框架判断科目"""
    text = (q.get('content', '') + ' ' + q.get('answer_framework', '') + ' ' + q.get('sample_essay', ''))
    scores = {subj: 0 for subj, _ in RULES}
    matched_keywords = {subj: [] for subj, _ in RULES}

    for subj, keywords in RULES:
        for kw in keywords:
            if kw in text:
                scores[subj] += 1
                if kw not in matched_keywords[subj]:
                    matched_keywords[subj].append(kw)

    if max(scores.values()) == 0:
        return None, matched_keywords, '无关键词匹配'

    best = max(scores, key=scores.get)
    top_score = scores[best]
    ties = [s for s, c in scores.items() if c == top_score and s != best]
    if ties:
        return None, matched_keywords, f'并列: {best}({top_score}) vs {",".join(f"{t}({scores[t]})" for t in ties)}'

    return best, matched_keywords[best], f'{best}({top_score})'


def main():
    with open(SEED_PATH, 'r', encoding='utf-8') as f:
        d = json.load(f)

    qs_610 = [q for q in d.get('exam_questions', []) if q.get('exam_paper_code') == '610']
    print(f'610 试卷共 {len(qs_610)} 题\n')

    results = []
    needs_review = []

    for q in qs_610:
        old_subj = q['subject']
        new_subj, matched, reason = classify_question(q)
        results.append({
            'id': q['id'],
            'year': q['year'],
            'old': old_subj,
            'new': new_subj if new_subj else '需复核',
            'content': q['content'][:80],
            'matched': matched,
            'reason': reason,
        })
        if new_subj is None:
            needs_review.append(results[-1])

    print('=== 全部分类结果 ===')
    for r in results:
        change = '' if r['old'] == r['new'] else f' [{r["old"]}→{r["new"]}]'
        print(f'{r["id"]} {r["year"]} {r["reason"]}{change}')
        print(f'  Q: {r["content"]}')
        if isinstance(r['matched'], dict):
            for s, kws in r['matched'].items():
                if kws:
                    print(f'  匹配: {s}={kws[:6]}')
        else:
            print(f'  匹配: {r["matched"][:6]}')
        print()

    print(f'\n=== 需人工复核: {len(needs_review)} 题 ===')
    for r in needs_review:
        print(f'{r["id"]} {r["year"]}: {r["content"]}')
        print(f'  理由: {r["reason"]}')
        if isinstance(r['matched'], dict):
            for s, kws in r['matched'].items():
                if kws:
                    print(f'  {s}: {kws}')
        print()

    new_dist = Counter(r['new'] for r in results)
    old_dist = Counter(r['old'] for r in results)
    print(f'\n=== 统计 ===')
    print(f'原分布: {dict(old_dist)}')
    print(f'新分布: {dict(new_dist)}')

    with open('/workspace/tools/610_classification.json', 'w', encoding='utf-8') as f:
        json.dump(results, f, ensure_ascii=False, indent=2)
    print(f'\n结果已保存到 /workspace/tools/610_classification.json')


if __name__ == '__main__':
    main()
