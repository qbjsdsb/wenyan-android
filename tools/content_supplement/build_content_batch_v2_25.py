def load_pages(file_name: str) -> list[dict[str, Any]]:
    payload = json.loads((OCR_ROOT / file_name).read_text(encoding="utf-8"))
    return payload["data"]["pages"]


def compact_ranges(numbers: list[int]) -> str:
    numbers = sorted(set(numbers))
    if not numbers:
        return ""
    chunks: list[str] = []
    start = previous = numbers[0]
    for number in numbers[1:]:
        if number == previous + 1:
            previous = number
            continue
        chunks.append(str(start) if start == previous else f"{start}–{previous}")
        start = previous = number
    chunks.append(str(start) if start == previous else f"{start}–{previous}")
    return "、".join(chunks)


def locate(file_name: str, anchors: list[str], window: tuple[int, int]) -> tuple[list[int], str]:
    """在教材印刷页窗口内逐锚点定位 OCR 物理页。"""

    offset = OFFSETS[file_name]
    low, high = window
    pages = load_pages(file_name)
    selected: set[int] = set()
    failures: list[str] = []
    for anchor in anchors:
        hits = [
            int(page["page_num"])
            for page in pages
            if low + offset <= int(page["page_num"]) <= high + offset
            and anchor in str(page.get("text", ""))
        ]
        if not hits:
            failures.append(f"{file_name} 印刷页 {low}–{high} 未找到锚点：{anchor}")
        else:
            selected.add(hits[0])
    if failures:
        raise RuntimeError("\n".join(failures))
    physical = sorted(selected)
    printed = sorted(number - offset for number in physical)
    return physical, compact_ranges(printed)


def entity(name: str, kind: str) -> dict[str, str]:
    return {"name": name, "type": kind, "normalized": name.replace("《", "").replace("》", "")}


