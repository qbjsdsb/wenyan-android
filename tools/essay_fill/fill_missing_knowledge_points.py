def make_point(idx, template):
    """根据模板生成完整知识点，补齐 id/conflict_flag/relations/source_count/merged_at/full_content。"""
    pid = f"kp_{idx:05d}"
    study_text = template["study_text"]
    return {
        "id": pid,
        "title": template["title"],
        "summary": template["summary"],
        "core_conclusion": template["core_conclusion"],
        "study_text": study_text,
        "full_content": study_text,  # full_content 与 study_text 一致（现有知识点皆如此）
        "subject": template["subject"],
        "tags": template["tags"],
        "difficulty": template["difficulty"],
        "conflict_flag": False,
        "entities": template["entities"],
        "relations": [],  # SeedDataLoader.computeRelatedIdsByTags 会基于 tags 派生 relatedIds
        "source_count": len(template["textbook_sources"]),
        "textbook_sources": template["textbook_sources"],
        "merged_at": "2026-07-31T00:00:00.000000",
        "exam_frequency": template["exam_frequency"],
    }


def clean_ocr_error_gap(questions):
    """清理论述题 knowledgeGaps 中的'原题OCR'错误条目（OCR 损坏标注，非知识点）。"""
    cleaned = 0
    for q in questions:
        if q.get("question_type") != "ESSAY":
            continue
        notes = q.get("notes")
        if isinstance(notes, str):
            try:
                notes_obj = json.loads(notes)
            except Exception:
                continue
            if isinstance(notes_obj, dict) and "knowledgeGaps" in notes_obj:
                gaps = notes_obj["knowledgeGaps"]
                new_gaps = [g for g in gaps
                            if not (isinstance(g, dict) and g.get("author", "") == "原题OCR")]
                if len(new_gaps) != len(gaps):
                    notes_obj["knowledgeGaps"] = new_gaps
                    q["notes"] = json.dumps(notes_obj, ensure_ascii=False)
                    cleaned += len(gaps) - len(new_gaps)
    return cleaned


